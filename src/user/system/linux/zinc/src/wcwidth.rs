//! The columns a character takes on a terminal, shared by the line editor and
//! zinc-next's prompt and parameter widths.

/// `iswprint`.
pub(crate) fn iswprint(c: u32) -> bool {
    if c < 0x20 || (0x7f..0xa0).contains(&c) {
        return false;
    }
    match char::from_u32(c) {
        None => false,
        Some(ch) => !ch.is_control() && !(0xfff0..=0xfff8).contains(&c) && c != 0xffff,
    }
}

