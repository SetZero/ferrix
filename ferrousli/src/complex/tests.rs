//! calling each function through `complex.h` for each of [`Z`] (and, for
//! `cpow`, the matching [`C`]) rounding to nearest, and for three of them
//! rounding downward. The `float` functions get the arguments converted to
//! `float` first. The exceptions include denormal, which x86-64 raises for a
//! subnormal operand.

