/// The bits of both parts, which tell -0 from 0 and one NaN from another.
pub(crate) fn bits(z: Complex) -> (u64, u64) {
    (z.re.to_bits(), z.im.to_bits())
}

/// [`bits`] for `float complex`.
pub(crate) fn bitsf(z: ComplexF) -> (u32, u32) {
    (z.re.to_bits(), z.im.to_bits())
}

/// Calls `call` in rounding mode `mode` with every flag clear, denormal
/// included, and returns its result with the exceptions it raised.
fn under<T>(mode: c_int, call: impl FnOnce() -> T) -> (T, c_int) {
    assert_eq!(fesetround(mode), 0);
    let _ = feclearexcept(FE_ALL_EXCEPT);
    let value = call();
    let raised = fetestexcept(FE_ALL_EXCEPT);
    let _ = fesetround(FE_TONEAREST);
    (value, raised)
}

