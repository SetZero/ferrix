/// Calls the function named `name` on `z` (and `c`), converting both to
/// `float` for a `float` function, in rounding mode `mode`. Returns the bits
/// of the result's parts, zero for the imaginary part of a real result, and
/// the exceptions raised; `None` for an unknown name.
fn call(name: &str, z: (f64, f64), c: (f64, f64), mode: c_int) -> Option<((u64, u64), c_int)> {
    let zd = Complex::new(z.0, z.1);
    let cd = Complex::new(c.0, c.1);
    let zf = ComplexF::new(z.0 as f32, z.1 as f32);
    let cf = ComplexF::new(c.0 as f32, c.1 as f32);
    let real = |x: f64| (x.to_bits(), 0);
    let realf = |x: f32| (u64::from(x.to_bits()), 0);
    let pairf = |r: ComplexF| (u64::from(r.re.to_bits()), u64::from(r.im.to_bits()));
    let result = match name {
        "cabs" => under(mode, || real(cabs(zd))),
        "cacos" => under(mode, || bits(cacos(zd))),
        "cacosh" => under(mode, || bits(cacosh(zd))),
        "carg" => under(mode, || real(carg(zd))),
        "casin" => under(mode, || bits(casin(zd))),
        "casinh" => under(mode, || bits(casinh(zd))),
        "catan" => under(mode, || bits(catan(zd))),
        "catanh" => under(mode, || bits(catanh(zd))),
        "ccos" => under(mode, || bits(ccos(zd))),
        "ccosh" => under(mode, || bits(ccosh(zd))),
        "cexp" => under(mode, || bits(cexp(zd))),
        "cimag" => under(mode, || real(cimag(zd))),
        "clog" => under(mode, || bits(clog(zd))),
        "conj" => under(mode, || bits(conj(zd))),
        "cpow" => under(mode, || bits(cpow(zd, cd))),
        "cproj" => under(mode, || bits(cproj(zd))),
        "creal" => under(mode, || real(creal(zd))),
        "csin" => under(mode, || bits(csin(zd))),
        "csinh" => under(mode, || bits(csinh(zd))),
        "csqrt" => under(mode, || bits(csqrt(zd))),
        "ctan" => under(mode, || bits(ctan(zd))),
        "ctanh" => under(mode, || bits(ctanh(zd))),
        "cabsf" => under(mode, || realf(cabsf(zf))),
        "cacosf" => under(mode, || pairf(cacosf(zf))),
        "cacoshf" => under(mode, || pairf(cacoshf(zf))),
        "cargf" => under(mode, || realf(cargf(zf))),
        "casinf" => under(mode, || pairf(casinf(zf))),
        "casinhf" => under(mode, || pairf(casinhf(zf))),
        "catanf" => under(mode, || pairf(catanf(zf))),
        "catanhf" => under(mode, || pairf(catanhf(zf))),
        "ccosf" => under(mode, || pairf(ccosf(zf))),
        "ccoshf" => under(mode, || pairf(ccoshf(zf))),
        "cexpf" => under(mode, || pairf(cexpf(zf))),
        "cimagf" => under(mode, || realf(cimagf(zf))),
        "clogf" => under(mode, || pairf(clogf(zf))),
        "conjf" => under(mode, || pairf(conjf(zf))),
        "cpowf" => under(mode, || pairf(cpowf(zf, cf))),
        "cprojf" => under(mode, || pairf(cprojf(zf))),
        "crealf" => under(mode, || realf(crealf(zf))),
        "csinf" => under(mode, || pairf(csinf(zf))),
        "csinhf" => under(mode, || pairf(csinhf(zf))),
        "csqrtf" => under(mode, || pairf(csqrtf(zf))),
        "ctanf" => under(mode, || pairf(ctanf(zf))),
        "ctanhf" => under(mode, || pairf(ctanhf(zf))),
        _ => return None,
    };
    Some(result)
}

#[test]
fn every_function_gives_musls_bits_and_exceptions() {
    let mut failures = Vec::new();
    let mut names = std::collections::BTreeSet::new();
    for &(name, down, index, re, im, except) in MUSL {
        let _ = names.insert(name);
        let mode = if down == 1 { FE_DOWNWARD } else { FE_TONEAREST };
        let (Some(&z), Some(&c)) = (Z.get(index), C.get(index)) else {
            failures.push(format!("{name}: no argument {index}"));
            continue;
        };
        match call(name, z, c, mode) {
            None => failures.push(format!("{name}: no such function")),
            Some((got, raised)) if got != (re, im) || raised != except => failures.push(format!(
                "{name}(#{index}) mode {mode:#x}: got {:#x} {:#x} raising {raised:#x}, \
                 musl {re:#x} {im:#x} raising {except:#x}",
                got.0, got.1
            )),
            Some(_) => {}
        }
    }
    assert_eq!(names.len(), 44, "the table covers every function");
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn square_roots_keep_the_sign_of_a_zero_on_the_branch_cut() {
    let root2 = hexf64!("0x1.6a09e667f3bcdp+0");
    let (z, raised) = under(FE_TONEAREST, || csqrt(Complex::new(-2.0, 0.0)));
    assert_eq!(bits(z), bits(Complex::new(0.0, root2)));
    assert_eq!(raised, FE_INEXACT);
    let z = csqrt(Complex::new(-2.0, -0.0));
    assert_eq!(bits(z), bits(Complex::new(0.0, -root2)));
    // csqrt(x ± i∞) = +∞ ± i∞, even for a NaN x.
    let z = csqrt(Complex::new(f64::NAN, f64::NEG_INFINITY));
    assert_eq!(
        bits(z),
        bits(Complex::new(f64::INFINITY, f64::NEG_INFINITY))
    );
    let z = csqrtf(ComplexF::new(-2.0, -0.0));
    assert_eq!(
        bitsf(z),
        bitsf(ComplexF::new(0.0, -hexf32!("0x1.6a09e6p+0")))
    );
}

#[test]
fn the_logarithm_of_zero_is_a_pole_and_its_argument_follows_the_signs() {
    let (z, raised) = under(FE_TONEAREST, || clog(Complex::new(-0.0, -0.0)));
    let pi = hexf64!("0x1.921fb54442d18p+1");
    assert_eq!(bits(z), bits(Complex::new(f64::NEG_INFINITY, -pi)));
    assert_eq!(raised, FE_DIVBYZERO);
    let z = clog(Complex::new(-2.0, 0.0));
    assert_eq!(
        bits(z),
        bits(Complex::new(hexf64!("0x1.62e42fefa39efp-1"), pi))
    );
    let (z, raised) = under(FE_TONEAREST, || clogf(ComplexF::new(0.0, 0.0)));
    assert_eq!(bitsf(z), bitsf(ComplexF::new(f32::NEG_INFINITY, 0.0)));
    assert_eq!(raised, FE_DIVBYZERO);
}

#[test]
fn infinities_give_annex_g_values_without_spurious_invalid() {
    let inf = f64::INFINITY;
    let (z, raised) = under(FE_TONEAREST, || cexp(Complex::new(-inf, -inf)));
    assert_eq!(bits(z), bits(Complex::new(0.0, 0.0)));
    assert_eq!(raised, 0);
    let (z, raised) = under(FE_TONEAREST, || ctanh(Complex::new(-inf, -inf)));
    assert_eq!(bits(z), bits(Complex::new(-1.0, -0.0)));
    assert_eq!(raised, 0);
    let (z, raised) = under(FE_TONEAREST, || catanh(Complex::new(1.0, 0.0)));
    assert_eq!(bits(z), bits(Complex::new(inf, 0.0)));
    assert_eq!(raised, FE_DIVBYZERO | FE_INEXACT);
    let (z, raised) = under(FE_TONEAREST, || cproj(Complex::new(f64::NAN, -inf)));
    assert_eq!(bits(z), bits(Complex::new(inf, -0.0)));
    assert_eq!(raised, 0);
}

#[test]
fn a_power_recovers_the_infinities_its_product_made_nans_of() {
    // log 2 = ln2 + i0, and (∞ + i∞)(ln2 + i0) as C first multiplies is
    // NaN + iNaN, from ∞ × 0; Annex G's recovery boxes ∞ + i∞ to 1 + i and
    // gets ∞ + i∞, whose exponential is ∞ + iNaN. Musl gives the same.
    let inf = f64::INFINITY;
    let (z, raised) = under(FE_TONEAREST, || {
        cpow(Complex::new(2.0, 0.0), Complex::new(inf, inf))
    });
    assert_eq!(bits(z), (inf.to_bits(), 0xfff8_0000_0000_0000));
    assert_eq!(raised, FE_INVALID | FE_INEXACT);
    let inf = f32::INFINITY;
    let (z, raised) = under(FE_TONEAREST, || {
        cpowf(ComplexF::new(2.0, 0.0), ComplexF::new(inf, inf))
    });
    assert_eq!(bitsf(z), (inf.to_bits(), 0xffc0_0000));
    assert_eq!(raised, FE_INVALID | FE_INEXACT);

    // 0^2: log 0 = -∞ + i0 raises divide-by-zero, the product -∞ + iNaN
    // raises invalid and needs no recovery, and exp(-∞ + iNaN) is 0 + i0.
    let (z, raised) = under(FE_TONEAREST, || {
        cpow(Complex::new(0.0, 0.0), Complex::new(2.0, 0.0))
    });
    assert_eq!(bits(z), bits(Complex::new(0.0, 0.0)));
    assert_eq!(raised, FE_INVALID | FE_DIVBYZERO);
}

