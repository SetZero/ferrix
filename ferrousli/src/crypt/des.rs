const TEST_LEN: usize = 21;

/// The key schedule: the 48-bit subkey of each of the 16 rounds, as two
/// 24-bit halves.
#[derive(Debug, Clone, Copy)]
struct ExpandedKey {
    /// The left halves.
    l: [u32; 16],
    /// The right halves.
    r: [u32; 16],
}

/// `table[row][column]`. Every column here is masked to the table's width
/// and every row is in range, so the zero for a miss is never used.
fn at<const ROWS: usize, const COLUMNS: usize>(
    table: &[[u32; COLUMNS]; ROWS],
    row: usize,
    column: u32,
) -> u32 {
    table
        .get(row)
        .and_then(|entries| entries.get(column as usize))
        .copied()
        .unwrap_or(0)
}

/// The value of a salt or count character, as UFC-crypt reads it where `char`
/// is signed: the alphabet [`B64`] maps to 0 to 63, and any other byte to
/// what the same arithmetic gives, modulo 64.
fn ascii_to_bin(character: u8) -> u32 {
    let signed = i32::from(i8::from_ne_bytes([character]));
    let mut value = signed - i32::from(b'.');
    if signed >= i32::from(b'A') {
        value = signed - (i32::from(b'A') - 12);
        if signed >= i32::from(b'a') {
            value = signed - (i32::from(b'a') - 38);
        }
    }
    (value & 0x3f).unsigned_abs()
}

/// Whether a traditional salt character would break the password file's
/// lines or fields, or is the end of the setting.
fn unsafe_in_passwd(character: u8) -> bool {
    matches!(character, 0 | b'\n' | b':')
}

/// The 24 salt bits, reversed: the salt's lowest bit swaps the highest pair of
/// bits in the expansion.
fn setup_salt(salt: u32) -> u32 {
    let mut saltbits = 0;
    for bit in 0..24 {
        if salt & (1 << bit) != 0 {
            saltbits |= 0x80_0000 >> bit;
        }
    }
    saltbits
}

/// The key schedule of the 8-byte `key`, whose low bit in each byte (DES's
/// parity bit) is ignored.
fn expand_key(key: &[u8; 8]) -> ExpandedKey {
    let [a0, a1, a2, a3, b0, b1, b2, b3] = *key;
    let raw0 = u32::from_be_bytes([a0, a1, a2, a3]);
    let raw1 = u32::from_be_bytes([b0, b1, b2, b3]);

    // The key permutation, splitting the key into two 28-bit halves.
    let mut k0 = 0;
    let mut k1 = 0;
    for (i, high) in [(0usize, 28u32), (1, 20), (2, 12), (3, 4)] {
        let low = high - 4;
        k0 |= at(&KEY_PERM_MASKL, i, (raw0 >> high) & 0xf)
            | at(&KEY_PERM_MASKL, i + 4, (raw1 >> high) & 0xf);
        k1 |= at(&KEY_PERM_MASKR, i << 1, (raw0 >> high) & 0xf);
        k1 |= at(&KEY_PERM_MASKR, (i << 1) + 1, (raw0 >> low) & 0xf)
            | at(&KEY_PERM_MASKR, i + 8, (raw1 >> low) & 0xf);
    }

    // Each round rotates the halves further and compresses them to 48 bits.
    let mut expanded = ExpandedKey {
        l: [0; 16],
        r: [0; 16],
    };
    let mut shifts = 0;
    for ((shift, left), right) in KEY_SHIFTS
        .iter()
        .zip(expanded.l.iter_mut())
        .zip(expanded.r.iter_mut())
    {
        shifts += u32::from(*shift);
        let t0 = (k0 << shifts) | (k0 >> (28 - shifts));
        let t1 = (k1 << shifts) | (k1 >> (28 - shifts));
        let mut kl = 0;
        let mut kr = 0;
        for (i, first) in [(0usize, 25u32), (1, 18), (2, 11), (3, 4)] {
            let second = first - 4;
            kl |= at(&COMP_MASKL0, i, (t0 >> first) & 7);
            kr |= at(&COMP_MASKR0, i, (t1 >> first) & 7);
            kl |= at(&COMP_MASKL1, i, (t0 >> second) & 0xf);
            kr |= at(&COMP_MASKR1, i, (t1 >> second) & 0xf);
        }
        *left = kl;
        *right = kr;
    }
    expanded
}

/// Enciphers the block `(l_in, r_in)` `count` times under `key`, with the
/// expansion's bits swapped wherever `saltbits` is set, and returns the result.
/// Both halves are big-endian.
fn des(l_in: u32, r_in: u32, count: u32, saltbits: u32, key: &ExpandedKey) -> (u32, u32) {
    // The initial permutation.
    let mut l = 0;
    let mut r = 0;
    if l_in | r_in != 0 {
        for (i, shift) in [
            (0usize, 28u32),
            (1, 24),
            (2, 20),
            (3, 16),
            (4, 12),
            (5, 8),
            (6, 4),
            (7, 0),
        ] {
            l |= at(&IP_MASKL, i, (l_in >> shift) & 0xf)
                | at(&IP_MASKL, i + 8, (r_in >> shift) & 0xf);
            r |= at(&IP_MASKR, i, (l_in >> shift) & 0xf)
                | at(&IP_MASKR, i + 8, (r_in >> shift) & 0xf);
        }
    }

    let mut f = 0;
    for _ in 0..count {
        for (kl, kr) in key.l.iter().zip(key.r.iter()) {
            // The expansion of R to 48 bits.
            let mut r48l = ((r & 0x0000_0001) << 23)
                | ((r & 0xf800_0000) >> 9)
                | ((r & 0x1f80_0000) >> 11)
                | ((r & 0x01f8_0000) >> 13)
                | ((r & 0x001f_8000) >> 15);
            let mut r48r = ((r & 0x0001_f800) << 7)
                | ((r & 0x0000_1f80) << 5)
                | ((r & 0x0000_01f8) << 3)
                | ((r & 0x0000_001f) << 1)
                | ((r & 0x8000_0000) >> 31);
            // The salt, then the subkey.
            f = (r48l ^ r48r) & saltbits;
            r48l ^= f ^ kl;
            r48r ^= f ^ kr;
            // The S-boxes, which shrink it back to 32 bits, and the P-box.
            f = at(&PSBOX, 0, r48l >> 18)
                | at(&PSBOX, 1, (r48l >> 12) & 0x3f)
                | at(&PSBOX, 2, (r48l >> 6) & 0x3f)
                | at(&PSBOX, 3, r48l & 0x3f)
                | at(&PSBOX, 4, r48r >> 18)
                | at(&PSBOX, 5, (r48r >> 12) & 0x3f)
                | at(&PSBOX, 6, (r48r >> 6) & 0x3f)
                | at(&PSBOX, 7, r48r & 0x3f);
            f ^= l;
            l = r;
            r = f;
        }
        r = l;
        l = f;
    }

    // The final permutation, the inverse of the initial one.
    let mut lo = 0;
    let mut ro = 0;
    for (i, high) in [(0usize, 28u32), (1, 20), (2, 12), (3, 4)] {
        let low = high - 4;
        ro |= at(&FP_MASKR, i, (l >> high) & 0xf) | at(&FP_MASKR, i + 4, (r >> high) & 0xf);
        lo |= at(&FP_MASKL, i, (l >> low) & 0xf) | at(&FP_MASKL, i + 4, (r >> low) & 0xf);
    }
    (lo, ro)
}

/// Enciphers the 8-byte `block` once under `key`, without salt.
fn cipher(block: &[u8; 8], key: &ExpandedKey) -> [u8; 8] {
    let [a0, a1, a2, a3, b0, b1, b2, b3] = *block;
    let (l, r) = des(
        u32::from_be_bytes([a0, a1, a2, a3]),
        u32::from_be_bytes([b0, b1, b2, b3]),
        1,
        0,
        key,
    );
    let [c0, c1, c2, c3] = l.to_be_bytes();
    let [d0, d1, d2, d3] = r.to_be_bytes();
    [c0, c1, c2, c3, d0, d1, d2, d3]
}

/// Appends the character of `value`'s low six bits for each of `shifts`.
fn push_characters(writer: &mut Writer<'_>, value: u32, shifts: &[u32]) -> Option<()> {
    for shift in shifts {
        let character = *B64.get(((value >> shift) & 0x3f) as usize)?;
        writer.push(&[character])?;
    }
    Some(())
}

/// The hash of `key` under `setting`, without the self test: musl's
/// `_crypt_extended_r_uut`.
fn hash(key: &[u8], setting: &[u8], out: &mut [u8]) -> Option<usize> {
    let character = |at: usize| setting.get(at).copied().unwrap_or(0);

    // The key's first 8 bytes, each shifted left by one, padded with zeroes.
    let mut keybuf = [0u8; 8];
    let mut rest = key;
    for slot in &mut keybuf {
        if let Some((&byte, tail)) = rest.split_first() {
            *slot = byte << 1;
            rest = tail;
        }
    }
    let mut expanded = expand_key(&keybuf);

    let mut writer = Writer::new(out);
    let count;
    let salt;
    if setting.first() == Some(&b'_') {
        // `_`, 4 characters of count and 4 of salt, least significant first.
        let read = |from: usize| -> Option<u32> {
            let mut value = 0;
            for (index, at) in (from..from + 4).enumerate() {
                let digit = ascii_to_bin(character(at));
                if B64.get(digit as usize) != Some(&character(at)) {
                    return None;
                }
                value |= digit << (index * 6);
            }
            Some(value)
        };
        count = read(1)?;
        if count == 0 {
            return None;
        }
        salt = read(5)?;

        // The rest of the key, 8 bytes at a time, each group folded into the
        // key by enciphering it with itself.
        while !rest.is_empty() {
            keybuf = cipher(&keybuf, &expanded);
            for slot in &mut keybuf {
                let Some((&byte, tail)) = rest.split_first() else {
                    break;
                };
                *slot ^= byte << 1;
                rest = tail;
            }
            expanded = expand_key(&keybuf);
        }

        writer.push(setting.get(..9)?)?;
    } else {
        // Two characters of salt, copied as they are.
        count = 25;
        if unsafe_in_passwd(character(0)) || unsafe_in_passwd(character(1)) {
            return None;
        }
        salt = (ascii_to_bin(character(1)) << 6) | ascii_to_bin(character(0));
        writer.push(&[character(0), character(1)])?;
    }

    let (r0, r1) = des(0, 0, count, setup_salt(salt), &expanded);

    // The 64 bits, most significant first, in 11 characters of 6 bits: the
    // last two bits are padding.
    push_characters(&mut writer, r0 >> 8, &[18, 12, 6, 0])?;
    push_characters(&mut writer, (r0 << 16) | (r1 >> 16), &[18, 12, 6, 0])?;
    push_characters(&mut writer, r1 << 2, &[12, 6, 0])?;
    writer.finish()
}

/// The DES hash of `key` under `setting`, written to `out` with a NUL: musl's
/// `__crypt_des`. Returns the length without the NUL, or `None` if the setting
/// is refused or the self test fails.
pub(super) fn descrypt(key: &[u8], setting: &[u8], out: &mut [u8]) -> Option<usize> {
    let result = hash(key, setting, out);

    let (test_setting, test_hash) = if setting.first() == Some(&b'_') {
        TEST_EXTENDED
    } else {
        TEST_TRADITIONAL
    };
    let mut test = [0u8; TEST_LEN];
    let passed = hash(TEST_KEY, test_setting, &mut test)
        .and_then(|len| test.get(..len))
        .is_some_and(|hashed| hashed == test_hash);

    if passed { result } else { None }
}

/// The raw 64 key bits installed by `setkey`. This interface is explicitly not
/// required to be thread-safe, but an atomic keeps concurrent C calls from
/// creating a Rust data race.
static BLOCK_KEY: AtomicU64 = AtomicU64::new(0);

/// Packs 64 bytes whose low bits represent a DES bit string, most-significant
/// bit first, into a machine value.
///
/// # Safety
///
/// `bits` must point to an array of at least 64 bytes.
unsafe fn pack_bits(bits: *const c_char) -> u64 {
    let mut value = 0_u64;
    for index in 0..64 {
        // SAFETY: the caller promises 64 readable bytes.
        let bit = unsafe { bits.wrapping_add(index).read() }.cast_unsigned() & 1;
        value = (value << 1) | u64::from(bit);
    }
    value
}

/// Installs the 64-bit DES key represented as 64 bytes containing bit values.
///
/// # Safety
///
/// `key` must point to an array of at least 64 bytes.
#[cfg_attr(not(test), unsafe(no_mangle))]
pub(crate) unsafe extern "C" fn setkey(key: *const c_char) {
    // SAFETY: the caller provides the array described by this function.
    BLOCK_KEY.store(unsafe { pack_bits(key) }, Ordering::Relaxed);
}

/// Encrypts or decrypts a 64-byte DES bit array in place under the key most
/// recently passed to [`setkey`]. A zero `direction` encrypts; nonzero
/// decrypts.
///
/// # Safety
///
/// `block` must point to an array of at least 64 writable bytes.
#[cfg_attr(not(test), unsafe(no_mangle))]
pub(crate) unsafe extern "C" fn encrypt(block: *mut c_char, direction: c_int) {
    // SAFETY: the caller promises a readable 64-byte array.
    let input = unsafe { pack_bits(block) }.to_be_bytes();
    let key = BLOCK_KEY.load(Ordering::Relaxed).to_be_bytes();
    let mut expanded = expand_key(&key);
    if direction != 0 {
        expanded.l.reverse();
        expanded.r.reverse();
    }
    let output = cipher(&input, &expanded);
    let value = u64::from_be_bytes(output);
    for index in 0..64 {
        let bit = ((value >> (63 - index)) & 1) as c_char;
        // SAFETY: the caller promises 64 writable bytes.
        unsafe { block.wrapping_add(index).write(bit) };
    }
}

