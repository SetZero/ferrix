//! The traditional DES password hash, and BSDi's extended `_` form of it.
//!
//! This is musl 1.2.5's `src/crypt/crypt_des.c` (MIT), ported whole. The
//! code descends from David Burren's FreeSec, reworked by Solar Designer and
//! given static tables by Rich Felker; its notice follows below.
//!
//! | Setting | Key | Iterations |
//! |---|---|---|
//! | two salt characters | its first 8 bytes | 25 |
//! | `_`, 4 characters of count, 4 of salt | every byte, folded into 8 | the count |
//!
//! Each key byte is shifted left by one, so its top bit is lost: DES has a
//! 56-bit key. The result is the setting's salt followed by 11 characters of
//! the 64-bit cipher text, 13 characters in all, or 20 in the extended form.
//!
//! The traditional hash is this old and this weak. It is here because POSIX
//! requires `crypt` to take a two-character salt, and old password files
//! still hold one.
//!
//! # Settings musl accepts and refuses
//!
//! These follow musl exactly, and musl follows UFC-crypt, the implementation
//! glibc once had:
//!
//! * A traditional salt character need not be in the alphabet. It is copied
//!   into the result as it is, and hashed as UFC-crypt reads it on a system
//!   whose `char` is signed ([`ascii_to_bin`]). Only a salt shorter than two
//!   characters, or holding a newline or a colon, is refused, because those
//!   would break the line and field structure of `/etc/passwd`. libxcrypt
//!   refuses every character outside the alphabet instead.
//! * An extended setting is refused unless its eight characters are all in
//!   the alphabet and its count is not zero.
//!
//! Every call hashes a known key under the same form of setting as well, and
//! a hash that does not come out as expected refuses the setting. That is
//! musl's self test: it catches a miscompiled table or shift, and in C it also
//! overwrites the stack the real hash used. Rust promises nothing about which
//! stack the second call uses, so here it is only the check.
